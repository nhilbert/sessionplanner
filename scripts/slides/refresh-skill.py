#!/usr/bin/env python3
"""Refreshes what the slide-build skill carries (.claude/skills/slide-build) from the repository:

    refresh-skill.py [--no-render]

  assets/slides.css, assets/themes/default.css   copies of src/slides (the installation's own themes are never copied)
  reference/catalogue.md                          the rules and every layout of src/domain/slideFormat.ts with its example
  reference/look/<layout>.png                     the example of every layout rendered in the default theme, 640 × 360

Run it after changing the stylesheet, the default theme or the catalogue; the tests check that the copies are
current. Rendering needs a headless Chromium ($CHROME; by default the one Playwright installs) and the fonts
from node_modules."""
import json, os, re, shutil, subprocess, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check import CSS, DEFAULT_THEME, REPO, find_chrome, furl, placeholder_png  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.join(REPO, '.claude', 'skills', 'slide-build')
DUMP = r'''
import { pathToFileURL } from 'node:url'
const m = await import(pathToFileURL(process.env.SP_REPO + '/src/domain/slideFormat.ts').href)
process.stdout.write(JSON.stringify({ format: m.SLIDE_FORMAT, layouts: m.SLIDE_LAYOUTS }))
'''
RULES = ['slide', 'elements', 'attributes', 'forbidden', 'svg', 'pictures', 'text', 'generated', 'choosing']
BREAK_BEFORE = 'section header footer ul ol li dl div figure figcaption aside table thead tbody tr blockquote cite svg g polygon rect circle path line text'.split()


def catalogue():
    r = subprocess.run(['node', '--no-warnings', '--input-type=module', '-e', DUMP], capture_output=True, text=True, env={**os.environ, 'SP_REPO': REPO})
    if r.returncode:
        sys.exit(f'node could not read the catalogue:\n{r.stderr.strip()}')
    return json.loads(r.stdout)


def pretty(frag):
    """The one-line example broken before block elements, indented by depth; short elements stay on one line."""
    lines, depth = [], 0
    for piece in re.split(r'(?=<(?:/?)(?:%s)\b)' % '|'.join(BREAK_BEFORE), frag):
        piece = piece.strip()
        if not piece:
            continue
        m = re.match(r'</([a-z0-9]+)>$', piece)
        if m and lines and re.match(rf'\s*<{m.group(1)}\b', lines[-1]) and f'</{m.group(1)}>' not in lines[-1]:
            lines[-1] += piece  # <li>…</li> on one line
            depth = max(depth - 1, 0)
            continue
        if piece.startswith('</'):
            depth = max(depth - 1, 0)
        lines.append('  ' * depth + piece)
        m = re.match(r'<([a-z0-9]+)', piece)
        if m and not piece.startswith('</') and m.group(1) not in ('img', 'br') and f'</{m.group(1)}>' not in piece:
            depth += 1
    return '\n'.join(lines)


def catalogue_md(data):
    fmt, layouts = data['format'], data['layouts']
    L = [
        '# The slide format – rules and catalogue',
        '',
        '<!-- Generated by scripts/slides/refresh-skill.py from src/domain/slideFormat.ts (what the connector serves as slide_format). Do not edit; change the module and run the script. -->',
        '',
        'The rules an agent needs to write a slide, and every layout with its purpose, its markup, its options, what fits on it and a complete example that the sanitiser leaves unchanged. The pictures show the example rendered in the default theme at 1280 × 720 (here at half size).',
        '',
        '## Rules',
        '',
    ]
    L += [f'- **{k}** – {fmt[k]}' for k in RULES]
    L += ['', 'Common classes:', ''] + [f'- `.{k}` – {v}' for k, v in fmt['classes'].items()]
    L += ['', '## Layouts', '', '| Layout | Used for | What fits |', '|---|---|---|']
    L += [f'| [`{l["layout"]}`](#{l["layout"]}) | {l["use"]}{" (generated by the app)" if l.get("generated") else ""} | {l.get("fits", "")} |' for l in layouts]
    for l in layouts:
        L += ['', f'### {l["layout"]}', '', f'![{l["layout"]}](look/{l["layout"]}.png)', '']
        L += [f'- **Use:** {l["use"]}' + ('. The app generates this slide from the workshop; write one only for a special case.' if l.get('generated') else '')]
        L += [f'- **Structure:** `{l["structure"]}`']
        if l.get('options'):
            L += [f'- **Options:** {l["options"]}']
        if l.get('fits'):
            L += [f'- **Fits:** {l["fits"]}']
        L += ['', '```html', pretty(l['example']), '```']
    return '\n'.join(L) + '\n'


def render_examples(layouts, chrome):
    look = os.path.join(SKILL, 'reference', 'look')
    os.makedirs(look, exist_ok=True)
    with tempfile.TemporaryDirectory() as root:
        deck = os.path.join(root, 'decks', 'catalogue')
        os.makedirs(deck)
        os.makedirs(os.path.join(root, 'assets'))
        placeholder_png(os.path.join(root, 'assets', 'placeholder.png'))
        for i, l in enumerate(layouts, 1):
            with open(os.path.join(deck, f'{i:02d}-{l["layout"]}.html'), 'w', encoding='utf-8') as f:
                f.write(re.sub(r'asset:[0-9a-f]+', 'assets/placeholder.png', l['example']) + '\n')
        with open(os.path.join(deck, 'deck.json'), 'w', encoding='utf-8') as f:
            json.dump({'title': 'Layout catalogue', 'theme': 'default', 'chrome': 'Beispieldeck'}, f)
        subprocess.run([sys.executable, os.path.join(HERE, 'build.py'), root], check=True, capture_output=True)
        page = os.path.join(root, 'catalogue.html')
        for i, l in enumerate(layouts, 1):
            out = os.path.join(look, f'{l["layout"]}.png')
            subprocess.run([chrome, '--headless', '--no-sandbox', '--disable-gpu', '--hide-scrollbars', '--virtual-time-budget=4000', '--window-size=1280,720', '--force-device-scale-factor=0.5', f'--screenshot={out}', f'{furl(page)}?only={i}'], capture_output=True, check=True)
    return look


def main():
    no_render = '--no-render' in sys.argv
    os.makedirs(os.path.join(SKILL, 'assets', 'themes'), exist_ok=True)
    os.makedirs(os.path.join(SKILL, 'reference'), exist_ok=True)
    shutil.copy(CSS, os.path.join(SKILL, 'assets', 'slides.css'))
    shutil.copy(DEFAULT_THEME, os.path.join(SKILL, 'assets', 'themes', 'default.css'))
    data = catalogue()
    with open(os.path.join(SKILL, 'reference', 'catalogue.md'), 'w', encoding='utf-8') as f:
        f.write(catalogue_md(data))
    print(f'{len(data["layouts"])} layouts → reference/catalogue.md; assets/slides.css and assets/themes/default.css copied')
    if no_render:
        return
    chrome = find_chrome()
    if not chrome:
        sys.exit('no headless Chromium found: set CHROME, or pass --no-render')
    look = render_examples(data['layouts'], chrome)
    print(f'{len(data["layouts"])} renderings → {os.path.relpath(look, REPO)}')


if __name__ == '__main__':
    main()
